/** Escape HTML special chars */
export function esc(str) {
  if (str == null) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/** Parse actData JSON string safely */
export function parseActData(actDataStr) {
  try { return JSON.parse(actDataStr || '{}'); }
  catch { return {}; }
}

/** Group color pill HTML (active style if isActive=true) */
export function groupPill(group, isActive = false) {
  if (!group) return '';
  const color = group.color ?? '#6366f1';
  const bg    = isActive ? color : color + '15';
  const border = isActive ? color : color + '55';
  const textColor = isActive ? '#fff' : color;
  return `<span class="group-pill" style="background:${bg};border-color:${border};color:${textColor}">
    ${esc(group.name)}
  </span>`;
}

/** Month key (YYYY-MM) → label (e.g. "Jan 2025") */
export function monthLabel(key) {
  if (!key) return key;
  const [y, m] = key.split('-');
  const d = new Date(Number(y), Number(m) - 1, 1);
  return d.toLocaleDateString('fr-FR', { month: 'short', year: 'numeric' });
}

/** Get last N months as YYYY-MM keys */
export function lastNMonths(n = 12) {
  const keys = [];
  const d = new Date();
  for (let i = n - 1; i >= 0; i--) {
    const t = new Date(d.getFullYear(), d.getMonth() - i, 1);
    const y = t.getFullYear();
    const m = String(t.getMonth() + 1).padStart(2, '0');
    keys.push(`${y}-${m}`);
  }
  return keys;
}

