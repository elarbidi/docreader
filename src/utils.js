/** Format date in fr-FR locale */
export function fmtDate(isoString) {
  if (!isoString) return '—';
  try {
    return new Date(isoString).toLocaleDateString('fr-FR', {
      day: '2-digit', month: 'short', year: 'numeric',
    });
  } catch { return isoString; }
}

/** Format datetime in fr-FR locale */
export function fmtDateTime(isoString) {
  if (!isoString) return '—';
  try {
    return new Date(isoString).toLocaleString('fr-FR', {
      day: '2-digit', month: 'short', year: 'numeric',
      hour: '2-digit', minute: '2-digit',
    });
  } catch { return isoString; }
}

/** Format monetary value in DH */
export function fmtDH(value) {
  if (value == null) return '—';
  return `${Number(value).toLocaleString('fr-FR', { minimumFractionDigits: 0 })} DH`;
}

/** Short ID display: last 6 chars uppercased */
export function shortId(id) {
  if (!id) return '—';
  return `#${id.slice(-6).toUpperCase()}`;
}

/** Patient display name */
export function fullName(patient) {
  if (!patient) return '—';
  return `${patient.firstName} ${patient.lastName}`;
}

/** Avatar initials: first char of firstName + first char of lastName */
export function initials(patient) {
  if (!patient) return '?';
  const f = patient.firstName?.[0] ?? '';
  const l = patient.lastName?.[0] ?? '';
  return (f + l).toUpperCase();
}

